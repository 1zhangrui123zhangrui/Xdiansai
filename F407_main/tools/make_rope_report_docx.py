NS_W = "http://schemas.openxmlformats.org/wordprocessingml/2006/main"
ET.register_namespace("w", NS_W)
W = f"{{{NS_W}}}"

# Word stores font size in half-points.
SIZE_XIAOER = 36   # 18 pt
SIZE_SAN = 32      # 16 pt
SIZE_SI = 28       # 14 pt
SIZE_XIAOSI = 24   # 12 pt
SIZE_WU = 21       # 10.5 pt
SIZE_XIAOWU = 18   # 9 pt
SIZE_LIU = 15      # 7.5 pt


def el(tag, attrs=None, text=None):
    node = ET.Element(W + tag, attrs or {})
    if text is not None:
        node.text = text
    return node


def qn(name):
    return W + name


def run(text, bold=False, size=SIZE_WU, font="宋体"):
    r = el("r")
    rpr = el("rPr")
    fonts = el("rFonts", {
        qn("ascii"): "Times New Roman",
        qn("hAnsi"): "Times New Roman",
        qn("eastAsia"): font,
    })
    rpr.append(fonts)
    rpr.append(el("sz", {qn("val"): str(size)}))
    rpr.append(el("szCs", {qn("val"): str(size)}))
    if bold:
        rpr.append(el("b"))
        rpr.append(el("bCs"))
    r.append(rpr)
    t = el("t", text=text)
    if text.startswith(" ") or text.endswith(" "):
        t.set("{http://www.w3.org/XML/1998/namespace}space", "preserve")
    r.append(t)
    return r


def para(text="", *, heading=0, center=False, bold=False, size=None, indent=True, font=None):
    p = el("p")
    ppr = el("pPr")
    if center:
        ppr.append(el("jc", {qn("val"): "center"}))
    if indent and heading == 0 and not center:
        ppr.append(el("ind", {qn("firstLineChars"): "200"}))
    spacing = {qn("line"): "360", qn("lineRule"): "auto"}
    if heading == 1:
        spacing.update({qn("before"): "360", qn("after"): "360"})
    elif heading == 2:
        spacing.update({qn("before"): "240", qn("after"): "240"})
    elif heading >= 3:
        spacing.update({qn("before"): "180", qn("after"): "120"})
    else:
        spacing.update({qn("after"): "40"})
    ppr.append(el("spacing", spacing))
    p.append(ppr)
    if size is None:
        size = SIZE_XIAOER if heading == 1 else SIZE_SAN if heading == 2 else SIZE_WU
    if font is None:
        font = "黑体" if heading else "宋体"

    plan_prefixes = ("方案一：", "方案二：", "方案三：", "对比选择：")
    if heading == 0 and not bold:
        for prefix in plan_prefixes:
            if text.startswith(prefix):
                p.append(run(prefix, bold=True, size=size, font=font))
                rest = text[len(prefix):]
                if rest:
                    p.append(run(rest, bold=False, size=size, font=font))
                return p

    p.append(run(text, bold=(bold or bool(heading)), size=size, font=font))
    return p


def cell(text, *, header=False, width=None):
    tc = el("tc")
    tcpr = el("tcPr")
    if width:
        tcpr.append(el("tcW", {qn("w"): str(width), qn("type"): "dxa"}))
    tc.append(tcpr)
    p = para(text, center=header, bold=False, size=SIZE_LIU, indent=False, font="宋体")
    tc.append(p)
    return tc


def table_title(text):
    return para(text, center=True, bold=True, size=SIZE_XIAOWU, indent=False, font="黑体")


def table(headers, rows):
    tbl = el("tbl")
    tblpr = el("tblPr")
    tblpr.append(el("tblW", {qn("w"): "0", qn("type"): "auto"}))
    borders = el("tblBorders")
    for name in ["top", "left", "bottom", "right", "insideH", "insideV"]:
        borders.append(el(name, {qn("val"): "single", qn("sz"): "6", qn("space"): "0", qn("color"): "000000"}))
    tblpr.append(borders)
    tblpr.append(el("tblLook", {qn("val"): "04A0"}))
    tbl.append(tblpr)
    tr = el("tr")
    for h in headers:
        tr.append(cell(h, header=True))
    tbl.append(tr)
    for row in rows:
        tr = el("tr")
        for item in row:
            tr.append(cell(str(item)))
        tbl.append(tr)
    return tbl


def page_break():
    p = el("p")
    r = el("r")
    r.append(el("br", {qn("type"): "page"}))
    p.append(r)
    return p


